def test_charts_render_deterministic_pngs(tmp_path):
    args = dict(
        categories=["language", "bi_tool"],
        series={
            "commercial": [Rate(540, 1353), Rate(459, 1353)],
            "federal": [Rate(4, 13), Rate(5, 13)],
        },
        title="Share of each market's skill tags",
        xlabel="% of the market's skill tags",
        demo=True,
        flagged=frozenset({("federal", "language")}),
    )
    a = grouped_barh(tmp_path / "a.png", **args)
    b = grouped_barh(tmp_path / "b.png", **args)
    assert a.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    assert a.read_bytes() == b.read_bytes()


def test_charts_refuse_unguarded_values_and_unlabelled_truncation(tmp_path):
    with pytest.raises(GuardrailError, match="Rates"):
        grouped_barh(tmp_path / "x.png", ["a"], {"s": [33.8]}, title="t", xlabel="x", demo=False)
    with pytest.raises(GuardrailError):
        grouped_barh(
            tmp_path / "x.png", ["a"], {"s": [Stat(1, 2)]}, title="t", xlabel="x", demo=False
        )
    floored = {"commercial": [skill_rate(72, 1483, "commercial")]}
    with pytest.raises(GuardrailError, match="truncation-floored"):
        grouped_barh(
            tmp_path / "x.png", ["SQL"], floored, title="Top skills", xlabel="%", demo=False
        )
    grouped_barh(
        tmp_path / "ok.png",
        ["SQL"],
        floored,
        title="Top skills",
        xlabel="% of jobs (truncation-floored)",
        demo=False,
    )


