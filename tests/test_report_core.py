def test_git_commit_prefers_the_env_override(monkeypatch):
    monkeypatch.setenv(prov.COMMIT_ENV, "abc123 (host checkout)")
    assert prov.git_commit() == "abc123 (host checkout)"


def test_git_commit_reads_the_repo_or_says_unknown(monkeypatch, tmp_path):
    monkeypatch.delenv(prov.COMMIT_ENV, raising=False)
    commit = prov.git_commit()
    assert len(commit.removesuffix("-dirty")) == 12
    assert prov.git_commit(tmp_path) == "unknown"  # not a git checkout


def test_collect_sorts_views_and_stamps_utc_now(monkeypatch):
    monkeypatch.setenv(prov.COMMIT_ENV, "c0ffee")
    p = Provenance.collect("jobmarket", {"v_b": 2, "v_a": 1})
    assert list(p.view_rows) == ["v_a", "v_b"] and p.git_commit == "c0ffee"
    assert p.generated_at.tzinfo is UTC and not p.is_demo


