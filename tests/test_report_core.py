def test_cells_accept_counts_labels_and_guardrail_types_only():
    assert render_cell(1483) == "1,483"
    assert render_cell(None) == "—"
    assert render_cell("SQL | Server") == "SQL \\| Server"
    assert render_cell(Rate(5, 10)) == "50.0% (5 of 10)"
    for bad in (33.8, "33.8%", "1,483", "+22.8 pp", "$98,500", True):
        with pytest.raises(GuardrailError):
            render_cell(bad)


def test_a_table_of_commercial_skill_rates_must_say_truncation_floored():
    doc = Doc("t", stamp(), "slug")
    rows = [["SQL", skill_rate(72, 1483, "commercial")]]
    with pytest.raises(GuardrailError, match="truncation-floored"):
        doc.table(["Skill", "Share of jobs"], rows)
    doc.table(["Skill", "Share of jobs (truncation-floored)"], rows)
    doc.table(["Skill", "Share"], rows, caption="Commercial rates are truncation-floored.")
    # federal rates aren't truncation-floored and need no label
    doc.table(["Skill", "Share"], [["SPSS", skill_rate(5, 70, "federal")]])
    with pytest.raises(GuardrailError, match="length"):
        doc.table(["a", "b"], [["only one"]])


def test_render_stamps_provenance_and_the_demo_banner():
    doc = Doc("Title", stamp("jobmarket_demo", v_a=3, v_b=1_200), "my-slug", subtitle="Sub")
    doc.placeholder("Headline", "Write one sentence.", [("SQL share", Rate(1, 4, unit="jobs"))])
    md = doc.render()
    assert md.startswith("<!-- Generated by `python -m src.reports my-slug`")
    assert f"> **{DEMO_BANNER}**" in md
    assert md.index(DEMO_BANNER) < md.index("# Title")
    for line in (
        "| Database | `jobmarket_demo` |",
        "| Generated at | 2026-10-27 03:00:00 UTC |",
        "| Git commit | `0123456789ab` |",
        "| Rows in `v_a` | 3 |",
        "| Rows in `v_b` | 1,200 |",
    ):
        assert line in md
    assert f"> **[{PLACEHOLDER_MARK}: Headline]** Write one sentence." in md
    assert "> - SQL share: 25.0% (1 of 4 jobs)" in md


def test_no_banner_on_a_real_database_name():
    assert DEMO_BANNER not in Doc("T", stamp("jobmarket"), "s").render()
    assert is_demo_database("jobmarket_demo") and is_demo_database("JOBMARKET_TEST")
    assert not is_demo_database("jobmarket")


