def stamp(database="jobmarket_demo", **rows):
    return Provenance(
        database=database,
        generated_at=datetime(2026, 10, 27, 3, 0, tzinfo=UTC),
        git_commit="0123456789ab",
        view_rows=rows or {"v_skill_top_by_source": 20},
    )


